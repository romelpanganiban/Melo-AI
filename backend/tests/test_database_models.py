class TestSettingsModel:
    """Tests for Settings model"""
    
    def test_settings_creation_with_defaults(self, test_db):
        """Test settings creation with default values"""
        # Create and insert into database to apply defaults
        settings = Settings()
        test_db.add(settings)
        test_db.commit()
        test_db.refresh(settings)
        
        assert settings.model_name == "qwen3:8b"
