"""Unit tests for database models"""

import pytest
from datetime import datetime
from database.models import Session as SessionModel, Message, Settings, Document, DocumentChunk
import uuid


class TestSessionModel:
    """Tests for Session model"""
    
    def test_session_creation(self):
        """Test session creation with explicit values"""
        test_id = str(uuid.uuid4())
        session = SessionModel(id=test_id, title="Test Session")
        assert session.id == test_id
        assert session.title == "Test Session"
    
    def test_session_auto_id_generation(self):
        """Test session auto-generates ID when not provided"""
        session = SessionModel(title="Test")
        # ID should be generated by default factory or on insert
        assert session.title == "Test"
    
    def test_session_custom_id(self):
        """Test session with custom ID"""
        custom_id = "custom-123"
        session = SessionModel(id=custom_id, title="Chat")
        assert session.id == custom_id
        assert session.title == "Chat"
    
    def test_session_repr(self):
        """Test session string representation"""
        session = SessionModel(id="123", title="Chat")
        repr_str = repr(session)
        assert "Session" in repr_str
        assert "123" in repr_str


